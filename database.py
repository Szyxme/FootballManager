def create_sqlite_tables():
    db = sqlite_connect()

    db.executescript("""
    CREATE TABLE IF NOT EXISTS users (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        username TEXT UNIQUE NOT NULL,
        password TEXT NOT NULL,
        is_admin INTEGER DEFAULT 0
    );

    CREATE TABLE IF NOT EXISTS clubs (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        budget INTEGER DEFAULT 1000000,
        user_id INTEGER NOT NULL REFERENCES users(id)
    );

    CREATE TABLE IF NOT EXISTS players (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        position TEXT NOT NULL,
        age INTEGER,
        rating INTEGER DEFAULT 50,
        club_id INTEGER NOT NULL REFERENCES clubs(id)
    );

    CREATE TABLE IF NOT EXISTS leagues (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        user_id INTEGER NOT NULL REFERENCES users(id)
    );

    CREATE TABLE IF NOT EXISTS league_teams (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        league_id INTEGER NOT NULL REFERENCES leagues(id),
        club_id INTEGER NOT NULL REFERENCES clubs(id),
        UNIQUE (league_id, club_id)
    );

    CREATE TABLE IF NOT EXISTS matches (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        league_id INTEGER NOT NULL REFERENCES leagues(id),
        home_club_id INTEGER NOT NULL REFERENCES clubs(id),
        away_club_id INTEGER NOT NULL REFERENCES clubs(id),
        home_score INTEGER,
        away_score INTEGER
    );

    CREATE TABLE IF NOT EXISTS transfers (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        player_id INTEGER NOT NULL REFERENCES players(id),
        from_club_id INTEGER REFERENCES clubs(id),
        to_club_id INTEGER NOT NULL REFERENCES clubs(id),
        price INTEGER DEFAULT 0
    );

    CREATE TABLE IF NOT EXISTS settings (
        id INTEGER PRIMARY KEY,
        site_name TEXT DEFAULT 'Football Manager',
        welcome_text TEXT DEFAULT 'Witaj w Football Manager!'
    );
    """)

    columns = db.execute("PRAGMA table_info(users)").fetchall()
    names = [column["name"] for column in columns]

    if "is_admin" not in names:
        db.execute(
            "ALTER TABLE users ADD COLUMN is_admin INTEGER DEFAULT 0"
        )

    db.execute("""
        INSERT OR IGNORE INTO settings (id, site_name, welcome_text)
        VALUES (1, 'Football Manager', 'Witaj w Football Manager!')
    """)

    db.commit()
    db.close()
